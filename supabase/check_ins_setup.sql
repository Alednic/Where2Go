-- Where2Go: simpan check-in milik pengguna yang sedang login (termasuk akun anonim).
-- Jalankan di Supabase SQL Editor. Tidak menghapus atau mengubah baris check-in yang ada.

begin;

create table if not exists public.check_ins (
    id bigint generated by default as identity primary key,
    place_id integer not null references public.places(id) on delete cascade,
    user_id uuid not null references auth.users(id) on delete cascade,
    vibe text not null check (vibe in ('QUIET', 'LIVELY', 'STUDY')),
    comfort_tags text[] not null default '{}',
    activity_tags text[] not null default '{}',
    price_level text not null check (price_level in ('LOW', 'MEDIUM', 'HIGH')),
    comment text,
    place_rating smallint check (place_rating between 1 and 5),
    points_earned integer not null default 10 check (points_earned = 10),
    client_request_id uuid not null default gen_random_uuid(),
    created_at timestamptz not null default now()
);

-- Kompatibel jika tabel check_ins sudah ada dari setup sebelumnya.
alter table public.check_ins
    add column if not exists client_request_id uuid;

update public.check_ins
set client_request_id = gen_random_uuid()
where client_request_id is null;

alter table public.check_ins
    alter column client_request_id set default gen_random_uuid(),
    alter column client_request_id set not null;

create unique index if not exists check_ins_user_request_id_uidx
    on public.check_ins (user_id, client_request_id);

create index if not exists check_ins_place_created_at_idx
    on public.check_ins (place_id, created_at desc);

alter table public.check_ins enable row level security;

revoke all on table public.check_ins from anon;
grant select, insert on table public.check_ins to authenticated;

do $$
declare
    check_ins_sequence regclass;
begin
    if not exists (
        select 1 from pg_policies
        where schemaname = 'public' and tablename = 'check_ins'
          and policyname = 'check_ins_select_own'
    ) then
        execute 'create policy check_ins_select_own on public.check_ins for select to authenticated using ((select auth.uid()) = user_id)';
    end if;

    if not exists (
        select 1 from pg_policies
        where schemaname = 'public' and tablename = 'check_ins'
          and policyname = 'check_ins_insert_own'
    ) then
        execute 'create policy check_ins_insert_own on public.check_ins for insert to authenticated with check ((select auth.uid()) = user_id)';
    end if;

    -- Restrictive policy mencegah policy permissive lama membolehkan user_id milik orang lain.
    if not exists (
        select 1 from pg_policies
        where schemaname = 'public' and tablename = 'check_ins'
          and policyname = 'check_ins_insert_user_id_restrictive'
    ) then
        execute 'create policy check_ins_insert_user_id_restrictive on public.check_ins as restrictive for insert to authenticated with check ((select auth.uid()) = user_id)';
    end if;

    check_ins_sequence := pg_get_serial_sequence('public.check_ins', 'id');
    if check_ins_sequence is not null then
        execute format('grant usage, select on sequence %s to authenticated', check_ins_sequence);
    end if;
end
$$;

commit;
