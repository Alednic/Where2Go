alter table public.place_submissions enable row level security;
grant select, insert on public.place_submissions to authenticated;
do $$
declare seq regclass;
begin
  seq := pg_get_serial_sequence('public.place_submissions', 'id');
  if seq is not null then execute format('grant usage, select on sequence %s to authenticated', seq); end if;
