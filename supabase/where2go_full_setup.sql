-- Where2Go production schema extension. Safe to re-run; does not delete existing rows.
begin;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Pengguna Where2Go',
  email text not null default '',
  username text not null default '',
  bio text not null default '',
  avatar_url text,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists profiles_username_unique
  on public.profiles (lower(username)) where username <> '';

create or replace function public.handle_new_where2go_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, display_name, email)
  values (new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'display_name',''), split_part(new.email,'@',1), 'Pengguna Where2Go'),
    coalesce(new.email,''))
  on conflict (id) do update set email = excluded.email,
    display_name = coalesce(nullif(public.profiles.display_name,'Pengguna Where2Go'), excluded.display_name);
  return new;
end;
$$;
drop trigger if exists where2go_auth_user_created on auth.users;
create trigger where2go_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_where2go_user();
insert into public.profiles (id, display_name, email)
select u.id, coalesce(nullif(u.raw_user_meta_data ->> 'display_name',''), split_part(u.email,'@',1), 'Pengguna Where2Go'),
  coalesce(u.email,'') from auth.users u on conflict (id) do nothing;

alter table public.profiles enable row level security;
grant select, insert, update on public.profiles to authenticated;
revoke update on public.profiles from authenticated;
grant update (display_name, username, bio, avatar_url, updated_at) on public.profiles to authenticated;
drop policy if exists profiles_read_self on public.profiles;
create policy profiles_read_self on public.profiles for select to authenticated using ((select auth.uid()) = id);
drop policy if exists profiles_insert_self on public.profiles;
create policy profiles_insert_self on public.profiles for insert to authenticated with check ((select auth.uid()) = id and role = 'user');
drop policy if exists profiles_update_self on public.profiles;
create policy profiles_update_self on public.profiles for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

create table if not exists public.user_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  tags text[] not null default '{}',
  updated_at timestamptz not null default now()
);
