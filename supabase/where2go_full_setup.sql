create or replace function public.weekly_top_places()
returns table (name text, address text, check_ins bigint)
language sql stable security definer set search_path = '' as $$
  select p.name::text, coalesce(p.address,'')::text, count(c.id)::bigint
  from public.places p join public.check_ins c on c.place_id = p.id
  where c.created_at >= date_trunc('week', now())
  group by p.id, p.name, p.address order by count(c.id) desc, p.name limit 50;
$$;

create or replace function public.weekly_top_contributors()
returns table (display_name text, check_ins bigint)
language sql stable security definer set search_path = '' as $$
  select coalesce(nullif(pr.username,''), nullif(pr.display_name,''), 'Pengguna Where2Go')::text,
    count(c.id)::bigint
  from public.check_ins c left join public.profiles pr on pr.id = c.user_id
  where c.created_at >= date_trunc('week', now())
  group by c.user_id, pr.username, pr.display_name
  order by count(c.id) desc limit 50;
$$;
grant execute on function public.weekly_top_places() to authenticated;
grant execute on function public.weekly_top_contributors() to authenticated;
revoke all on function public.weekly_top_places() from public, anon;
revoke all on function public.weekly_top_contributors() from public, anon;

create or replace function public.owner_dashboard_stats()
returns table (place_id bigint, name text, check_ins bigint, leading_vibe text)
language sql stable security definer set search_path = '' as $$
  select p.id::bigint, p.name::text, count(c.id)::bigint,
    coalesce((select c2.vibe from public.check_ins c2 where c2.place_id = p.id
      group by c2.vibe order by count(*) desc limit 1), 'Belum ada')::text
  from public.places p left join public.check_ins c on c.place_id = p.id
  where p.owner_id = auth.uid()
  group by p.id, p.name order by count(c.id) desc, p.name;
$$;
grant execute on function public.owner_dashboard_stats() to authenticated;
revoke all on function public.owner_dashboard_stats() from public, anon;

-- Admin approves/rejects submissions. Approval also publishes a real place for Explore/Map.
create or replace function public.review_place_submission(submission_id bigint, approved boolean)
returns void language plpgsql security definer set search_path = '' as $$
declare
  s public.place_submissions%rowtype;
begin
  if not exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin') then
    raise exception 'Akses hanya untuk admin.' using errcode = '42501';
  end if;
  select * into s from public.place_submissions where id = submission_id and status = 'PENDING' for update;
  if not found then raise exception 'Pendaftaran tidak ditemukan atau sudah ditinjau.'; end if;

  update public.place_submissions set status = case when approved then 'APPROVED' else 'REJECTED' end,
    updated_at = now() where id = submission_id;

  if approved then
    insert into public.places (name, address, latitude, longitude, description, opening_hours,
      image_url, facilities, card_tags, owner_id, category, phone, vibe, price_level, rating, min_order)
    values (s.name, s.address, s.latitude, s.longitude, s.description, s.opening_hours,
      s.image_url, s.facilities, array[s.category], s.owner_id, s.category, s.phone, 'QUIET', 'MEDIUM', 0, s.min_order);
  end if;
end;
$$;
grant execute on function public.review_place_submission(bigint, boolean) to authenticated;
revoke all on function public.review_place_submission(bigint, boolean) from public, anon;

